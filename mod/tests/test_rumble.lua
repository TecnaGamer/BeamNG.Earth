-- luajit mod/tests/test_rumble.lua (rumble.lua: only actual carriageway edges/undivided centerlines are candidates)
local dir = (arg[0]:match('^(.*)[/\\]') or '.')
local T = dofile(dir .. '/testlib.lua')
dofile(dir .. '/stubs.lua')
local R = require('beamngEarth/rumble')

local twoWayMiddle = R.hitZones(0.4, 3.4, false)
T.check(twoWayMiddle.centre and not twoWayMiddle.edge, 'undivided centerline: near center stripe')
local twoWayLane = R.hitZones(1.7, 3.4, false)
T.check(not twoWayLane.centre and not twoWayLane.edge, 'normal lane position: no sound zone')
local twoWayEdge = R.hitZones(2.7, 3.4, false)
T.check(not twoWayEdge.centre and twoWayEdge.edge, 'outer edge line: candidate')
local dividedMiddle = R.hitZones(0.4, 6.0, true)
T.check(not dividedMiddle.centre and not dividedMiddle.edge, 'divided carriageway: no median/centerline sound')
local innerLaneDivider = R.hitZones(3.0, 6.0, true)
T.check(not innerLaneDivider.centre and not innerLaneDivider.edge, 'same-direction lane divider: ignored')
local freewayOuterEdge = R.hitZones(5.4, 6.0, true)
T.check(freewayOuterEdge.edge, 'outer freeway line: candidate')

T.done('test_rumble')
