"""build_blob.sh's last step: the trampoline and filter bytes into enginepatch_code.py (or --check it)."""
import hashlib
import sys

tramp, filt, dst = (open(sys.argv[1], "rb").read(), open(sys.argv[2], "rb").read(), sys.argv[3])
check = "--check" in sys.argv[4:]
if len(tramp) > 0x100 or len(filt) > 0xF00:
    raise SystemExit(f"write_code: too large (trampoline {len(tramp)}, filter {len(filt)})")


def hexlines(b):
    h = b.hex()
    return "\n".join(f'    "{h[i:i + 96]}"' for i in range(0, len(h), 96))


text = f'''"""Machine code of the Windows dtsmooth patch (enginepatch.py), generated by tools/gcpatch/win/build_blob.sh from
dtsmooth_tramp.asm and dtsmooth_filter.c (tools/gcpatch/bngearth_dtfilter.h): do not edit; rebuild."""

TRAMP = bytes.fromhex(
{hexlines(tramp)}
)
FILTER = bytes.fromhex(
{hexlines(filt)}
)
SHA256 = "{hashlib.sha256(tramp + filt).hexdigest()}"
'''
if check:
    try:
        old = open(dst).read()
    except OSError:
        old = ""
    if old != text:
        raise SystemExit("write_code: enginepatch_code.py differs from a fresh build (run tools/gcpatch/win/build_blob.sh)")
    print("enginepatch_code.py: up to date")
else:
    open(dst, "w").write(text)
    print(f"wrote {dst}: trampoline {len(tramp)} bytes, filter {len(filt)} bytes")
