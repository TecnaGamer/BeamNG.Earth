"""build_terfast.sh's last step: the stub, the code and its entry offsets into enginepatch_terfast_code.py (or --check)."""
import hashlib
import sys

stub, code, nm, dst = (open(sys.argv[1], "rb").read(), open(sys.argv[2], "rb").read(), open(sys.argv[3]).read(),
                       sys.argv[4])
check = "--check" in sys.argv[5:]
if len(stub) > 0x40 or len(code) > 0xF00:
    raise SystemExit(f"write_terfast: too large (stub {len(stub)}, code {len(code)})")
sym = {}
for line in nm.splitlines():
    p = line.split()
    if len(p) == 3:
        sym[p[2]] = int(p[0], 16)
entries = {k: sym[k] for k in ("tf_bounds", "tf_mats", "tf_holes")}
if sym.get("tf_state") != 0x1000 or not all(0x100 <= v < 0x100 + len(code) for v in entries.values()):
    raise SystemExit(f"write_terfast: unexpected layout {entries} state {sym.get('tf_state')}")


def hexlines(b):
    h = b.hex()
    return "\n".join(f'    "{h[i:i + 96]}"' for i in range(0, len(h), 96))


text = f'''"""Machine code of the Windows terfast patch (enginepatch_terfast.py), generated by
tools/gcpatch/win/build_terfast.sh from terfast_stub.asm and terfast_win.c: do not edit; rebuild."""

STUB = bytes.fromhex(
{hexlines(stub)}
)
CODE = bytes.fromhex(
{hexlines(code)}
)
ENTRY = {entries!r}
SHA256 = "{hashlib.sha256(stub + code).hexdigest()}"
'''
if check:
    try:
        old = open(dst).read()
    except OSError:
        old = ""
    if old != text:
        raise SystemExit("write_terfast: enginepatch_terfast_code.py differs from a fresh build "
                         "(run tools/gcpatch/win/build_terfast.sh)")
    print("enginepatch_terfast_code.py: up to date")
else:
    open(dst, "w").write(text)
    print(f"wrote {dst}: stub {len(stub)} bytes, code {len(code)} bytes, entries {entries}")
