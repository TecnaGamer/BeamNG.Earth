#!/usr/bin/env python3
"""Measure pinned road-plan reuse with the real grader and synthetic geographic input.

Two clients use different anchor frames and separate disk caches. Transfer uses the
actual loopback HTTP service. This does not measure BeamNG FPS, real-world loading,
internet latency, or complete terrain identity. Requires development test fixtures.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import platform
import statistics
import sys
import tempfile
import threading
import time
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "server"), str(ROOT / "server" / "tests"), str(ROOT / "tools")]


def cpu_name():
    if os.name == "nt":
        import winreg
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                           r"HARDWARE\DESCRIPTION\System\CentralProcessor\0") as key:
            return winreg.QueryValueEx(key, "ProcessorNameString")[0].strip()
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def run_once():
    import numpy as np
    import fast
    import geodesy
    import grading
    import plancache
    import revisit
    import worldbundle
    import world_cache
    from test_grading import FakeMD
    from test_roads import features, FRAME, LAT, LON

    fast.require(fast.MIN_VERSION, "shared road-plan benchmark")
    description = {"roads_m": [[[-300, 20], [300, 20]], [[0, -300], [0, 300]]],
                   "classes": ["residential", "secondary"], "elevation_m": 10.0,
                   "sample_count": 256, "sample_east_m": [-200, 200],
                   "sample_north_m": [-30, 60], "origin_lat_lon": [LAT, LON]}
    feats = features(description["roads_m"], description["classes"])
    la, lo, _ = FRAME.enu_to_geodetic(np.linspace(-200, 200, 256), np.linspace(-30, 60, 256), 0.0)
    base = np.zeros(256)
    frames = [FRAME, geodesy.EnuFrame(LAT + 0.01, LON + 0.01)]
    elevation_calls = 0

    def raw(lat, lon):
        nonlocal elevation_calls
        elevation_calls += 1
        return np.full(np.shape(lat), 10.0)
    source_digest = hashlib.sha256(worldbundle.canonical(description)).hexdigest()

    def grader(frame, md):
        return grading.Grader(frame, md, raw)

    def timed(fn):
        start = time.perf_counter()
        value = fn()
        return value, (time.perf_counter() - start) * 1000

    # Isolate from the user's active pin, planner run and revisit cache.
    environment = dict(os.environ)
    environment.pop(worldbundle.ENV, None)
    environment[plancache.RUN_ENV] = "bundle-benchmark"
    with mock.patch.dict(os.environ, environment, clear=True), mock.patch.object(revisit, "ON", False), \
            tempfile.TemporaryDirectory(prefix="beam-earth-bundle-benchmark-") as temporary:
        root = Path(temporary)
        local_ms, local_calls, local_elevation_calls, local_values = [], [], [], []
        baseline_start = time.perf_counter()
        for frame in frames:
            md = FakeMD(feats)
            g = grader(frame, md)
            previous_calls = elevation_calls
            value, elapsed = timed(lambda: g.apply(la, lo, base))
            local_ms.append(elapsed)
            local_calls.append(md.calls)
            local_elevation_calls.append(elevation_calls - previous_calls)
            local_values.append(value)
        baseline_cold_ms = (time.perf_counter() - baseline_start) * 1000
        np.testing.assert_array_equal(local_values[0], local_values[1])

        shared_start = time.perf_counter()
        producer_md = FakeMD(feats)
        producer = grader(FRAME, producer_md)
        producer.shared = plancache.for_grader(root / "producer", producer, None, None)
        previous_calls = elevation_calls
        expected, produce_ms = timed(lambda: producer.apply(la, lo, base))
        producer_elevation_calls = elevation_calls - previous_calls
        np.testing.assert_array_equal(expected, local_values[0])
        bundle_path = root / "published"
        manifest, export_ms = timed(lambda: worldbundle.build_bundle(
            producer.shared.dir, bundle_path, {}, source_digest,
            ["Synthetic fixture generated by BeamNG.Earth tests; no external geographic data."]))
        server, serve_setup_ms = timed(lambda: world_cache.make_server(bundle_path, port=0))
        worker = threading.Thread(target=server.serve_forever, kwargs={"poll_interval": 0.02}, daemon=True)
        worker.start()
        try:
            url = f"http://127.0.0.1:{server.server_port}"
            def receive(index):
                return world_cache.fetch(url, root / f"client-{index}", manifest["id"])
            start = time.perf_counter()
            with ThreadPoolExecutor(max_workers=2) as pool:
                downloads = list(pool.map(receive, range(2)))
            fetch_ms = (time.perf_counter() - start) * 1000
            # HTTP handlers update counters after sending the response; wait for
            # that bookkeeping before using the snapshot to check warm reuse.
            expected_transfer = {key: sum(stats[key] for path, stats in downloads)
                                 for key in ("requests", "bytes")}
            deadline = time.monotonic() + 2.0
            while server.stats != expected_transfer and time.monotonic() < deadline:
                time.sleep(0.001)
            if server.stats != expected_transfer:
                raise AssertionError("Server and client transfer counters disagree")
            served_after_cold = dict(server.stats)
            pinned_ms, pinned_calls, pinned_elevation_calls, plan_reads = [], [], [], []
            for frame, (path, stats) in zip(frames, downloads):
                md = FakeMD(feats)
                g = grader(frame, md)
                with mock.patch.dict(os.environ, {worldbundle.ENV: str(path)}):
                    g.shared = plancache.for_grader(root / "unused-local", g, None, None)
                    previous_calls = elevation_calls
                    value, elapsed = timed(lambda: g.apply(la, lo, base))
                np.testing.assert_array_equal(value, expected)
                if md.calls or elevation_calls != previous_calls:
                    raise AssertionError("Pinned consumer fetched source road or elevation data")
                pinned_ms.append(elapsed)
                pinned_calls.append(md.calls)
                pinned_elevation_calls.append(elevation_calls - previous_calls)
                plan_reads.append(g.shared.stats["read"])
            shared_cold_ms = (time.perf_counter() - shared_start) * 1000
            warm, warm_ms = timed(lambda: [receive(index) for index in range(2)])
            if server.stats != served_after_cold or any(stats["requests"] for path, stats in warm):
                raise AssertionError("Warm bundle reuse performed network requests")
            if not any(expected != base):
                raise AssertionError("Fixture did not exercise actual road grading")
            return {
                "fixture": description, "manifest_id": manifest["id"],
                "generator": manifest["generator"], "numpy": np.__version__,
                "baseline": {"client_grade_ms": local_ms, "total_grade_ms": sum(local_ms),
                             "cold_total_ms": baseline_cold_ms,
                             "source_cell_calls": local_calls, "source_elevation_calls": local_elevation_calls},
                "shared": {"producer_grade_ms": produce_ms, "producer_source_cell_calls": producer_md.calls,
                           "producer_elevation_calls": producer_elevation_calls,
                           "export_ms": export_ms, "serve_setup_ms": serve_setup_ms,
                           "concurrent_client_fetch_ms": fetch_ms, "client_grade_ms": pinned_ms,
                           "client_source_cell_calls": pinned_calls, "client_plan_reads": plan_reads,
                           "client_source_elevation_calls": pinned_elevation_calls,
                           "cold_total_ms": shared_cold_ms,
                           "warm_fetch_ms": warm_ms, "client_transfers": [stats for path, stats in downloads],
                           "warm_requests": sum(stats["requests"] for path, stats in warm),
                           "server_transfers": served_after_cold, "artifacts": len(manifest["artifacts"]),
                           "unique_blobs": len({a["sha256"] for a in manifest["artifacts"]})},
                "verification": {"equal_geographic_sample_heights": True,
                                 "different_anchor_frames": True, "isolated_client_directories": True,
                                 "pinned_source_cell_calls": 0, "pinned_source_elevation_calls": 0,
                                 "warm_network_requests": 0,
                                 "height_sha256": hashlib.sha256(expected.tobytes()).hexdigest()},
            }
        finally:
            server.shutdown()
            server.server_close()
            worker.join(timeout=5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--iterations", type=int, default=5)
    parser.add_argument("--output", type=Path, help="Optional JSON output path")
    args = parser.parse_args()
    if not 1 <= args.iterations <= 30:
        parser.error("--iterations must be between 1 and 30")
    rows = [run_once() for _ in range(args.iterations)]
    if len({r["verification"]["height_sha256"] for r in rows}) != 1:
        raise AssertionError("Geographic heights changed between identical fixture iterations")
    if len({r["manifest_id"] for r in rows}) != 1:
        raise AssertionError("Manifest identity changed between identical fixture iterations")
    result = {
        "schema": 1, "fixture": "two synthetic roads, flat 10 m elevation, 256 geographic samples",
        "scope": "Road-plan generation and loopback bundle distribution; two isolated Graders in one process",
        "limitations": ["No BeamNG/BeamMP runtime", "No real geographic provider downloads",
                        "No FPS, full-world loading or cross-machine determinism measurement",
                        "Producer/export/verification overhead is included; this tiny fixture may be slower overall",
                        "Caches are application-cold per iteration; OS filesystem cache is not flushed"],
        "hardware": {"cpu": cpu_name(), "logical_processors": os.cpu_count(),
                     "os": platform.platform(), "python": platform.python_version()},
        "iterations": rows,
        "median_ms": {"baseline_two_client_cold": statistics.median(r["baseline"]["cold_total_ms"] for r in rows),
                      "baseline_two_client_grading": statistics.median(r["baseline"]["total_grade_ms"] for r in rows),
                      "shared_cold_total": statistics.median(r["shared"]["cold_total_ms"] for r in rows),
                      "shared_two_client_grading": statistics.median(sum(r["shared"]["client_grade_ms"]) for r in rows),
                      "shared_warm_fetch": statistics.median(r["shared"]["warm_fetch_ms"] for r in rows)},
    }
    text = json.dumps(result, indent=2, allow_nan=False)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
