#!/usr/bin/env python3
"""Builds server/superlatives_data.py: the map search's answers to "highest bridge in Switzerland" (geocode.py).

No search service can answer such a question, and the Wikidata Query Service takes 6 to 30+ seconds (often a timeout), so
the answers are read from Wikidata once, here, and ship with the app: the top few of each kind per country and for the
world, with their coordinates. Run by hand now and then:

    python tools/build_superlatives.py

Data: Wikidata (CC0).
"""
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

UA = "BeamNG.Earth superlatives builder (+https://github.com/XavierCraggs/BeamNG.Earth)"   # fork: was TecnaGamer
ENDPOINT = "https://query.wikidata.org/sparql"
OUT = Path(__file__).resolve().parents[1] / "server" / "superlatives_data.py"
TOP = 5
CHUNK = 40
# key -> (class, property, smallest value kept, largest believable value)
KINDS = {
    "bridge_height": ("Q12280", "P2048", 25, 650),
    "bridge_length": ("Q12280", "P2043", 300, 200000),
    "tunnel_length": ("Q44377", "P2043", 500, 70000),     # (a longer one: Iran's ancient water tunnels)
    "pass_elevation": ("Q133056", "P2044", 300, 6000),
    "dam_height": ("Q12323", "P2048", 25, 350),
}


def sparql(query, tries=4):
    url = ENDPOINT + "?" + urllib.parse.urlencode({"query": query, "format": "json"})
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/sparql-results+json"})
            with urllib.request.urlopen(req, timeout=70) as r:
                return json.load(r)["results"]["bindings"]
        except (urllib.error.URLError, TimeoutError, ValueError) as e:
            print(f"  retry {i + 1}: {e}", file=sys.stderr)
            time.sleep(10 * (i + 1))
    return None


def subclasses(cls):
    rows = sparql(f"SELECT DISTINCT ?t WHERE {{ ?t wdt:P279* wd:{cls} . }}")
    return [r["t"]["value"].rsplit("/", 1)[1] for r in rows or []] or [cls]


def point(wkt):
    lon, lat = wkt[wkt.index("(") + 1:wkt.index(")")].split()
    return round(float(lat), 5), round(float(lon), 5)


def rows_of(types, prop, low, high):
    values = " ".join("wd:" + t for t in types)
    return sparql(f"""SELECT ?item ?iso ?v ?coord ?de ?en WHERE {{
      VALUES ?t {{ {values} }}
      ?item wdt:P31 ?t; wdt:P625 ?coord; p:{prop}/psn:{prop}/wikibase:quantityAmount ?v.
      FILTER(?v >= {low} && ?v <= {high})
      OPTIONAL {{ ?item wdt:P17/wdt:P297 ?iso. }}
      OPTIONAL {{ ?item rdfs:label ?de. FILTER(LANG(?de) = "de") }}
      OPTIONAL {{ ?item rdfs:label ?en. FILTER(LANG(?en) = "en") }}
    }}""")


def build():
    out = {}
    for key, (cls, prop, low, high) in KINDS.items():
        types = subclasses(cls)
        print(key, len(types), "classes", flush=True)
        items = {}
        for i in range(0, len(types), CHUNK):
            rows = rows_of(types[i:i + CHUNK], prop, low, high)
            if rows is None:
                print("  chunk failed", i, flush=True)
                continue
            for r in rows:
                q = r["item"]["value"].rsplit("/", 1)[1]
                name_en = r.get("en", {}).get("value")
                name_de = r.get("de", {}).get("value")
                if not (name_en or name_de):
                    continue
                it = items.setdefault(q, {"en": name_en or name_de, "de": name_de or name_en,
                                          "v": 0.0, "p": point(r["coord"]["value"]), "cc": set()})
                it["v"] = max(it["v"], float(r["v"]["value"]))
                if r.get("iso"):
                    it["cc"].add(r["iso"]["value"])
            time.sleep(1.0)
        ranked = sorted(items.values(), key=lambda it: -it["v"])
        table = {"": ranked[:TOP]}
        for it in ranked:
            for cc in it["cc"]:
                row = table.setdefault(cc, [])
                if len(row) < TOP:
                    row.append(it)
        out[key] = {cc: [(it["en"], it["de"], round(it["v"]), it["p"][0], it["p"][1]) for it in row]
                    for cc, row in sorted(table.items())}
        print(" ", len(items), "items,", len(table), "areas", flush=True)
    return out


def countries():
    """Country names and short names in the languages people type -> ISO code."""
    rows = sparql("""SELECT ?iso ?l WHERE { ?c wdt:P297 ?iso. { ?c rdfs:label ?l } UNION { ?c skos:altLabel ?l }
      FILTER(LANG(?l) IN ("de", "en", "fr", "it", "es", "nl", "pl")) }""") or []
    return {r["l"]["value"]: r["iso"]["value"] for r in rows}


def main():
    names = countries()
    print(len(names), "country names", flush=True)
    data = build()
    lines = ['"""GENERATED by tools/build_superlatives.py from Wikidata (CC0). Do not edit by hand.',
             "TABLE: kind -> ISO country ('' the world) -> [(English name, German name, metres, lat, lon)], the largest first.",
             "COUNTRIES: country name in several languages -> ISO country.",
             '"""', "TABLE = {"]
    for key, table in data.items():
        lines.append(f"    {key!r}: {{")
        for cc, rows in table.items():
            lines.append(f"        {cc!r}: {rows!r},")
        lines.append("    },")
    lines.append("}")
    lines.append(f"COUNTRIES = {dict(sorted(names.items()))!r}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
